/**
 * The words of SQL, as data: which ones the formatter writes in capitals,
 * and which ones and which functions the completion offers on each engine.
 *
 * `RESERVED` is deliberately the words that are never a column in practice.
 * `name`, `type`, `status`, `key`, `value`, `date`, `user`, `count` are all
 * words of some dialect and all columns of somebody's table; capitalising a
 * column because it spells a keyword would be the formatter rewriting the
 * reader's schema.
 */
