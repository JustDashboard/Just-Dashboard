const unique = (list: string[]) => [...new Set(list)]

/** The keywords and functions the completion offers for a driver. */
export function vocabularyOf(driver: string): Vocabulary {
  const own = Object.hasOwn(VOCABULARIES, driver) ? VOCABULARIES[driver] : undefined
  return {
    keywords: unique([...COMMON_KEYWORDS, ...(own?.keywords ?? [])]),
    functions: unique([...COMMON_FUNCTIONS, ...(own?.functions ?? [])]),
  }
}
