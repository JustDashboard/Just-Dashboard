func upgradeFacts(version string, num int) *PostgresServerFacts {
	return &PostgresServerFacts{
		Version: version, VersionNum: num, DataDirectory: "/var/lib/postgresql/data",
		Databases:    []PostgresDatabase{{Name: "app", Bytes: 8 << 20}, {Name: "postgres", Bytes: 7 << 20}},
		Roles:        []string{"jd"},
		FileSettings: map[string]string{"max_connections": "100", "listen_addresses": "*"},
		HBA:          []string{"local all all trust", "host all all all scram-sha-256"},
		Settings:     []string{"work_mem", "shared_buffers", "shared_preload_libraries", "max_connections"},
		Available:    map[string]string{"plpgsql": "1.0", "pg_trgm": "1.6", "hstore": "1.8", "vector": "0.8.0"},
		Loadable:     map[string]bool{},
	}
}

func checkOf(checks []UpgradeCheck, id string) (UpgradeCheck, bool) {
	for _, c := range checks {
		if c.ID == id {
			return c, true
		}
	}
	return UpgradeCheck{}, false
}

// A server with nothing unusual about it is reported in four lines, none of
// which stops the upgrade: the checks for what it does not have — prepared
// transactions, tablespaces, replication, edited sign-in rules — are not
// drawn at all.
func TestPostgresUpgradeChecksOnAQuietServer(t *testing.T) {
	from, to := upgradeFacts("16.15", 160015), upgradeFacts("17.11", 170011)
	installed := map[string][]PostgresExtension{
		"app":      {{Name: "plpgsql", Version: "1.0"}, {Name: "pg_trgm", Version: "1.6"}},
		"postgres": {{Name: "plpgsql", Version: "1.0"}},
	}
	checks := PostgresUpgradeChecks(from, to, installed)
	ids := []string{}
	for _, c := range checks {
		ids = append(ids, c.ID)
		if c.Verdict != UpgradeOK {
			t.Errorf("%s = %s: %s", c.ID, c.Verdict, c.Detail)
		}
	}
	if want := []string{"version", "extensions", "sessions", "parameters"}; !slices.Equal(ids, want) {
		t.Errorf("checks = %v, want %v", ids, want)
	}
	if c, _ := checkOf(checks, "version"); c.Detail != "PostgreSQL 16.15 to 17.11." {
		t.Errorf("version = %q", c.Detail)
	}
	if c, _ := checkOf(checks, "extensions"); !slices.Equal(c.Items, []string{"pg_trgm 1.6"}) {
		t.Errorf("extensions = %+v", c)
	}
}

// What the copy cannot carry stops it before anything changes, each in its
// own words: an extension the new image lacks, a library the server preloads
// that it does not have, a transaction prepared for a second phase, and a
// tablespace in a directory the new container does not have.
func TestPostgresUpgradeChecksStopWhatTheCopyCannotCarry(t *testing.T) {
	from, to := upgradeFacts("16.15", 160015), upgradeFacts("17.11", 170011)
	from.Preload = "pg_stat_statements, auto_explain"
	to.Loadable = map[string]bool{"pg_stat_statements": true}
	from.Prepared = []string{"tx-7"}
	from.Tablespaces = []PostgresTablespace{{Name: "fast", Location: "/mnt/nvme"}}
	installed := map[string][]PostgresExtension{
		"app":  {{Name: "postgis", Version: "3.5.0"}, {Name: "vector", Version: "0.7.4"}},
		"shop": {{Name: "postgis", Version: "3.5.0"}},
	}
	checks := PostgresUpgradeChecks(from, to, installed)
	for id, item := range map[string]string{
		"extensions":  "postgis in app",
		"libraries":   "auto_explain",
		"prepared":    "tx-7",
		"tablespaces": "fast at /mnt/nvme",
	} {
		c, ok := checkOf(checks, id)
		if !ok || c.Verdict != UpgradeBlocker || !slices.Contains(c.Items, item) {
			t.Errorf("%s = %+v, want a blocker naming %q", id, c, item)
		}
	}
	if c, _ := checkOf(checks, "extensions"); !slices.Equal(c.Items, []string{"postgis in app", "postgis in shop"}) {
		t.Errorf("every database missing an extension is named: %v", c.Items)
	}
	// A release that is not newer is not an upgrade.
	same := upgradeFacts("16.2", 160002)
	if c, _ := checkOf(PostgresUpgradeChecks(from, same, nil), "version"); c.Verdict != UpgradeBlocker {
		t.Errorf("16 to 16 = %+v", c)
	}
}

// What the copy carries differently is said and does not stop it: sessions
// that will be disconnected, replication that has to be set up again, an
// extension that arrives at the new image's version, parameters edited by
// hand and sign-in rules that are not part of a dump.
func TestPostgresUpgradeChecksSayWhatChanges(t *testing.T) {
	from, to := upgradeFacts("16.15", 160015), upgradeFacts("17.11", 170011)
	from.Sessions = 3
	from.Slots = []PostgresSlot{{Name: "debezium", Type: "logical"}}
	from.Subscriptions = []string{"orders_feed"}
	from.FileSettings["shared_buffers"] = "1GB"
	from.HBA = append(from.HBA, "host app reporter 10.0.0.0/8 scram-sha-256")
	from.AutoConf = "# Do not edit this file manually!\nwork_mem = '64MB'\nold_snapshot_threshold = '1h'\n"
	installed := map[string][]PostgresExtension{"app": {{Name: "vector", Version: "0.7.4"}}}
	checks := PostgresUpgradeChecks(from, to, installed)

	sessions, _ := checkOf(checks, "sessions")
	if sessions.Verdict != UpgradeWarning || !strings.HasPrefix(sessions.Detail, "3 sessions are connected now. They are disconnected") {
		t.Errorf("sessions = %+v", sessions)
	}
	replication, _ := checkOf(checks, "replication")
	if replication.Verdict != UpgradeWarning || !slices.Equal(replication.Items, []string{"slot debezium (logical)", "subscription orders_feed"}) {
		t.Errorf("replication = %+v", replication)
	}
	extensions, _ := checkOf(checks, "extensions")
	if extensions.Verdict != UpgradeOK || !slices.Equal(extensions.Items, []string{"vector 0.7.4 → 0.8.0"}) {
		t.Errorf("extensions = %+v", extensions)
	}
	parameters, _ := checkOf(checks, "parameters")
	if parameters.Verdict != UpgradeWarning ||
		!slices.Equal(parameters.Items, []string{"work_mem", "not carried: shared_buffers = 1GB"}) ||
		!strings.Contains(parameters.Detail, "old_snapshot_threshold is no longer in the new release and is left out.") {
		t.Errorf("parameters = %+v", parameters)
	}
	hba, _ := checkOf(checks, "hba")
	if hba.Verdict != UpgradeWarning || !slices.Equal(hba.Items, []string{"host app reporter 10.0.0.0/8 scram-sha-256"}) {
		t.Errorf("hba = %+v", hba)
	}
	for _, c := range checks {
		if c.Verdict == UpgradeBlocker {
			t.Errorf("%s stops the upgrade: %s", c.ID, c.Detail)
		}
	}
}

// postgresql.auto.conf is carried as text, because a list read back and set
// again as one string is one entry with a comma in its name. A parameter the
// new release has no more is left out — the server would not start with it —
// and an extension's own parameter is kept before its library defines it.
func TestCarryPostgresParametersKeepsTheFileAndLeavesOutWhatIsGone(t *testing.T) {
	text := "# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\n" +
		"shared_preload_libraries = 'pg_stat_statements, auto_explain'\n" +
		"work_mem = '64MB'\n" +
		"old_snapshot_threshold = '1h'\n" +
		"pg_stat_statements.max = '10000'\n" +
		"Max_Connections = '200'"
	file, carried, dropped := CarryPostgresParameters(text, []string{"shared_preload_libraries", "work_mem", "max_connections"})
	want := "# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\n" +
		"shared_preload_libraries = 'pg_stat_statements, auto_explain'\n" +
		"work_mem = '64MB'\n" +
		"pg_stat_statements.max = '10000'\n" +
		"Max_Connections = '200'\n"
	if file != want {
		t.Errorf("file =\n%s\nwant\n%s", file, want)
	}
	if !slices.Equal(carried, []string{"shared_preload_libraries", "work_mem", "pg_stat_statements.max", "max_connections"}) {
		t.Errorf("carried = %v", carried)
	}
	if !slices.Equal(dropped, []string{"old_snapshot_threshold"}) {
		t.Errorf("dropped = %v", dropped)
	}
	if file, carried, dropped := CarryPostgresParameters("", nil); file != "" || len(carried) != 0 || len(dropped) != 0 {
		t.Errorf("an empty file = %q %v %v", file, carried, dropped)
	}
}

const sampleGlobals = `\restrict Kq1oTAmvrIMOWlVRdl2VfOZlWOmHBTs
--
-- PostgreSQL database cluster dump
--

SET default_transaction_read_only = off;

SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;

--
-- Roles
--

CREATE ROLE jd;
ALTER ROLE jd WITH SUPERUSER INHERIT CREATEROLE CREATEDB LOGIN REPLICATION BYPASSRLS PASSWORD 'SCRAM-SHA-256$4096:abc$def:ghi';
CREATE ROLE "Reporting";
ALTER ROLE "Reporting" WITH NOSUPERUSER INHERIT NOCREATEROLE NOCREATEDB LOGIN NOREPLICATION NOBYPASSRLS;
COMMENT ON ROLE "Reporting" IS 'reads
CREATE ROLE jd;
nothing else';

--
-- User Configurations
--

ALTER ROLE "Reporting" SET search_path TO 'reports', 'public';

GRANT pg_read_all_data TO "Reporting" WITH INHERIT TRUE GRANTED BY jd;

\unrestrict Kq1oTAmvrIMOWlVRdl2VfOZlWOmHBTs
`

// The roles' script is cut where psql cuts it and the one statement the new
// server cannot run — creating the account it was itself created with — is
// left out by statement, not by line: a line inside a comment's text that
// reads the same is part of that text.
func TestPostgresGlobalsLeavesOutTheRoleTheServerAlreadyHas(t *testing.T) {
	statements, err := PostgresGlobals(strings.NewReader(sampleGlobals), "jd")
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"SET default_transaction_read_only = off",
		"SET client_encoding = 'UTF8'",
		"SET standard_conforming_strings = on",
		"ALTER ROLE jd WITH SUPERUSER INHERIT CREATEROLE CREATEDB LOGIN REPLICATION BYPASSRLS PASSWORD 'SCRAM-SHA-256$4096:abc$def:ghi'",
		`CREATE ROLE "Reporting"`,
		`ALTER ROLE "Reporting" WITH NOSUPERUSER INHERIT NOCREATEROLE NOCREATEDB LOGIN NOREPLICATION NOBYPASSRLS`,
		"COMMENT ON ROLE \"Reporting\" IS 'reads\nCREATE ROLE jd;\nnothing else'",
		`ALTER ROLE "Reporting" SET search_path TO 'reports', 'public'`,
		`GRANT pg_read_all_data TO "Reporting" WITH INHERIT TRUE GRANTED BY jd`,
	}
	if !reflect.DeepEqual(statements, want) {
		t.Errorf("statements =\n%q\nwant\n%q", statements, want)
	}

	// A bootstrap account whose name pg_dump quotes is matched quoted.
	quoted, err := PostgresGlobals(strings.NewReader("CREATE ROLE \"Admin\";\nALTER ROLE \"Admin\" WITH LOGIN;\n"), "Admin")
	if err != nil || !slices.Equal(quoted, []string{`ALTER ROLE "Admin" WITH LOGIN`}) {
		t.Errorf("quoted bootstrap = %q, %v", quoted, err)
	}

	// Nothing in the script is a client's to run.
	for _, script := range []string{
		"CREATE ROLE app;\n\\! rm -rf /\n",
		"CREATE ROLE app;\n\\connect other\n",
		"COPY t FROM stdin;\n1\n\\.\n",
	} {
		if _, err := PostgresGlobals(strings.NewReader(script), "jd"); err == nil {
			t.Errorf("%q was read as roles", script)
		}
	}
}

// A database is named as a value in a connection string, so a name with an
// equals sign in it cannot turn the client's -d into a string of its own.
func TestPostgresConnInfoQuotesTheName(t *testing.T) {
	for name, want := range map[string]string{
		"app":                     "dbname='app'",
		"host=evil.example user=": `dbname='host=evil.example user='`,
		`it's`:                    `dbname='it\'s'`,
		`back\slash`:              `dbname='back\\slash'`,
	} {
		if got := PostgresConnInfo(name); got != want {
			t.Errorf("PostgresConnInfo(%q) = %s, want %s", name, got, want)
		}
	}
}

// The switch to reads only is taken back to exactly what the file held: a
// value it had of its own, or none.
func TestPostgresReadOnlyIsGivenBackAsItWas(t *testing.T) {
	if got := PostgresTakeReadsOnly(); !slices.Equal(got, []string{"ALTER SYSTEM SET default_transaction_read_only = on", "SELECT pg_reload_conf()"}) {
		t.Errorf("take reads only = %q", got)
	}
	if got := PostgresTakeWrites("", true); !slices.Equal(got, []string{"ALTER SYSTEM RESET default_transaction_read_only", "SELECT pg_reload_conf()"}) {
		t.Errorf("take writes with no prior value = %q", got)
	}
	if got := PostgresTakeWrites("on", false); !slices.Equal(got, []string{"ALTER SYSTEM SET default_transaction_read_only = 'on'"}) {
		t.Errorf("take writes back to a prior value, without a reload = %q", got)
	}
	text := "work_mem = '4MB'\ndefault_transaction_read_only = 'off'\ndefault_transaction_read_only = 'on'\nsearch_path = '\"$user\", public'\n"
	if v, ok := PostgresAutoConfValue(text, "default_transaction_read_only"); !ok || v != "on" {
		t.Errorf("the last line for a name is the one read: %q %v", v, ok)
	}
	if v, ok := PostgresAutoConfValue(text, "search_path"); !ok || v != `"$user", public` {
		t.Errorf("search_path = %q %v", v, ok)
	}
	if _, ok := PostgresAutoConfValue(text, "shared_buffers"); ok {
		t.Error("a parameter the file does not set was found")
	}
	if got := PostgresDropDatabase(`we"ird`); got != `DROP DATABASE "we""ird"` {
		t.Errorf("drop = %s", got)
	}
	if got := PostgresLoad("auto_explain'; --"); got != `LOAD 'auto_explain''; --'` {
		t.Errorf("load = %s", got)
	}
}

func TestPostgresVersionsAndLibraries(t *testing.T) {
	for num, want := range map[int]int{160015: 16, 170000: 17, 180001: 18, 90624: 9, 100023: 10} {
		if got := PostgresMajor(num); got != want {
			t.Errorf("PostgresMajor(%d) = %d, want %d", num, got, want)
		}
	}
	if got := PostgresPreloadLibraries(` pg_stat_statements ,"auto_explain",, `); !slices.Equal(got, []string{"pg_stat_statements", "auto_explain"}) {
		t.Errorf("libraries = %q", got)
	}
	if got := PostgresPreloadLibraries(""); len(got) != 0 {
		t.Errorf("no libraries = %q", got)
	}
}

// A copy matches when every table has its rows; one missing or short is
// named with both numbers.
func TestPostgresCopyDifferences(t *testing.T) {
	before := map[string]int64{"public.orders": 120, "public.customers": 8, "public.empty": 0}
	if got := PostgresCopyDifferences("app", before, map[string]int64{"public.orders": 120, "public.customers": 8, "public.empty": 0}); len(got) != 0 {
		t.Errorf("an exact copy = %v", got)
	}
	got := PostgresCopyDifferences("app", before, map[string]int64{"public.orders": 119, "public.empty": 0})
	if want := []string{"app: public.customers is missing", "app: public.orders has 119 rows, not 120"}; !slices.Equal(got, want) {
		t.Errorf("differences = %v, want %v", got, want)
	}
	counts, err := ParsePostgresRowCounts([]byte(`{"public.orders": 120}`))
	if err != nil || counts["public.orders"] != 120 {
		t.Errorf("counts = %v %v", counts, err)
	}
}

func TestParsePostgresServerFacts(t *testing.T) {
	facts, err := ParsePostgresServerFacts([]byte(`{"version":"16.15","versionNum":160015,"databases":[{"name":"app","bytes":7798319,"template":false}],
		"roles":["jd"],"sessions":2,"slots":[],"subscriptions":[],"prepared":[],"tablespaces":[],"preload":"",
		"autoConf":"# Do not edit\n","fileSettings":{"max_connections":"100"},"hba":["local all all trust"],
		"settings":["work_mem"],"available":{"plpgsql":"1.0"}}`))
	if err != nil {
		t.Fatal(err)
	}
	if facts.VersionNum != 160015 || facts.Databases[0].Name != "app" || facts.Sessions != 2 || facts.Available["plpgsql"] != "1.0" {
		t.Errorf("facts = %+v", facts)
	}
	if _, err := ParsePostgresServerFacts([]byte(`{"version":""}`)); err == nil {
		t.Error("an answer with no release was read")
	}
	// The query names the dashboard's own sessions the way its connections
	// name themselves.
	if !strings.Contains(PostgresServerFactsQuery, "application_name <> 'just-dashboard'") {
		t.Error("the sessions count does not leave the dashboard's own out")
	}
}
