package openapigen

import (
	"bytes"
	_ "embed"
	"fmt"
	"strconv"
	"strings"
)

// The TypeScript client: types.ts (an interface per object, a constant
// object and its union type per vocabulary) and client.ts (the runtime from
// client.ts.tmpl, then one function per operation over fetch). It has no
// dependencies, so it runs in a browser, Node, Deno or Bun as it is.

//go:embed client.ts.tmpl
var tsRuntime string

const tsHeader = "// Generated by openapigen from docs/api/deploy-openapi.json. Do not edit.\n" +
	"// Regenerate with: cd backend && JD_UPDATE_SDK=1 go test ./internal/api -run TestTheCommittedSDKsAreCurrent\n\n"

func generateTypeScript(api *API) (map[string][]byte, error) {
	return map[string][]byte{
		"types.ts":  tsTypes(api),
		"client.ts": tsClient(api),
	}, nil
}

// tsType is a TypeScript type for a value.
func tsType(t *Type) string {
	var base string
	switch t.Kind {
	case KindAny:
		return "unknown"
	case KindString, KindTime, KindBytes:
		base = "string"
	case KindInt64, KindInt32, KindFloat:
		base = "number"
	case KindBool:
		base = "boolean"
	case KindNamed:
		base = t.Name
	case KindArray:
		elem := tsType(t.Elem)
		if strings.Contains(elem, " ") {
			elem = "(" + elem + ")"
		}
		base = elem + "[]"
	case KindMap:
		base = "Record<string, " + tsType(t.Elem) + ">"
	case KindUnion:
		options := make([]string, 0, len(t.Options))
		for _, o := range t.Options {
			options = append(options, tsType(o))
		}
		base = strings.Join(options, " | ")
	}
	if t.Nullable {
		return base + " | null"
	}
	return base
}

func writeTSComment(b *bytes.Buffer, indent, text string) {
	text = strings.TrimSpace(text)
	if text == "" {
		return
	}
	text = strings.ReplaceAll(text, "*/", "*∕")
	paragraphs := strings.Split(text, "\n\n")
	if len(paragraphs) == 1 && len(indent)+len(text)+7 <= 100 {
		b.WriteString(indent + "/** " + text + " */\n")
		return
	}
	b.WriteString(indent + "/**\n")
	for i, paragraph := range paragraphs {
		if i > 0 {
			b.WriteString(indent + " *\n")
		}
		for _, line := range wrap(paragraph, 96-len(indent)) {
			b.WriteString(indent + " * " + line + "\n")
		}
	}
	b.WriteString(indent + " */\n")
}

func tsProperty(name string) string {
	if identifier(name) {
		return name
	}
	return strconv.Quote(name)
}

func tsTypes(api *API) []byte {
	var b bytes.Buffer
	b.WriteString(tsHeader)
	for i, d := range api.Decls {
		if i > 0 {
			b.WriteString("\n")
		}
		if d.Enum != nil {
			writeTSComment(&b, "", declComment(d, "One of the values of "+d.Source+"."))
			fmt.Fprintf(&b, "export const %s = {\n", d.Name)
			for _, c := range enumConstants(d) {
				fmt.Fprintf(&b, "  %s: %s,\n", strings.TrimPrefix(c.ident, d.Name), strconv.Quote(c.value))
			}
			b.WriteString("} as const\n")
			fmt.Fprintf(&b, "export type %s = (typeof %s)[keyof typeof %s]\n", d.Name, d.Name, d.Name)
			continue
		}
		summary := d.Source + " in the dashboard's source."
		if d.Inline {
			summary = "The object " + d.Source + " spells out."
		}
		writeTSComment(&b, "", declComment(d, summary))
		if len(d.Fields) == 0 {
			fmt.Fprintf(&b, "export type %s = Record<string, never>\n", d.Name)
			continue
		}
		fmt.Fprintf(&b, "export interface %s {\n", d.Name)
		for _, f := range d.Fields {
			doc := f.Doc
			if f.WriteOnly && !strings.Contains(doc, "never read back") {
				doc = strings.TrimSpace(doc + " Write-only: it is sent and never read back.")
			}
			writeTSComment(&b, "  ", doc)
			fmt.Fprintf(&b, "  %s?: %s\n", tsProperty(f.JSON), tsType(f.Type))
		}
		b.WriteString("}\n")
	}
	return b.Bytes()
}

// tsNames is every declaration an operation's signature names, for the
// import from types.ts.
func tsNames(api *API) []string {
	need := map[string]bool{}
	var mark func(t *Type)
	mark = func(t *Type) {
		if t == nil {
			return
		}
		switch t.Kind {
		case KindNamed:
			need[t.Name] = true
		case KindArray, KindMap:
			mark(t.Elem)
		case KindUnion:
			for _, o := range t.Options {
				mark(o)
			}
		}
	}
	for _, op := range api.Ops {
		for _, p := range op.PathParams {
			mark(p.Type)
		}
		if op.Stream {
			continue
		}
		for _, q := range op.QueryParams {
			mark(q.Type)
		}
		mark(op.Body)
		mark(op.Response)
	}
	return sortedKeys(need)
}

func tsClient(api *API) []byte {
	var b bytes.Buffer
	b.WriteString(tsHeader)
	if names := tsNames(api); len(names) > 0 {
		b.WriteString("import type {\n")
		for _, n := range names {
			b.WriteString("  " + n + ",\n")
		}
		b.WriteString("} from \"./types\"\n\n")
	}
	runtime := strings.ReplaceAll(tsRuntime, "{{BasePath}}", api.BasePath)
	var fields, assign strings.Builder
	for _, f := range api.ErrorFields {
		if f.JSON == "message" {
			continue
		}
		var doc bytes.Buffer
		writeTSComment(&doc, "  ", f.Doc)
		fields.WriteString(doc.String())
		fmt.Fprintf(&fields, "  readonly %s?: %s\n", tsProperty(f.JSON), tsType(f.Type))
		fmt.Fprintf(&assign, "    this.%s = envelope?.%s as %s | undefined\n", f.JSON, f.JSON, tsType(f.Type))
	}
	runtime = strings.ReplaceAll(runtime, "  // {{ErrorFields}}\n", fields.String())
	runtime = strings.ReplaceAll(runtime, "    // {{ErrorAssign}}\n", assign.String())
	b.WriteString(runtime)
	for _, op := range api.Ops {
		b.WriteString("\n")
		writeTSOperation(&b, op)
	}
	return b.Bytes()
}

func tsPathExpr(op *Operation) string {
	byName := map[string]Param{}
	for _, p := range op.PathParams {
		byName[p.Name] = p
	}
	var sb strings.Builder
	sb.WriteString("`")
	path := op.Path
	for path != "" {
		open := strings.Index(path, "{")
		closeAt := strings.Index(path, "}")
		if open < 0 || closeAt < open {
			sb.WriteString(path)
			break
		}
		sb.WriteString(path[:open])
		name := path[open+1 : closeAt]
		path = path[closeAt+1:]
		if p, ok := byName[name]; ok {
			sb.WriteString("${pathParam(" + p.TS + ")}")
		} else {
			sb.WriteString("{" + name + "}")
		}
	}
	sb.WriteString("`")
	return sb.String()
}

func writeTSOperation(b *bytes.Buffer, op *Operation) {
	name := strings.ToLower(op.Go[:1]) + op.Go[1:]
	if op.ID != "" && identifier(op.ID) && !tsReserved[op.ID] {
		name = op.ID
	}
	if op.Stream {
		writeTSComment(b, "", operationComment(op, name+"Url")+
			"\n\nIt is a WebSocket stream rather than a call, so this gives its address (ws:// or wss://) for a WebSocket client that sends the key as a bearer token; a browser's WebSocket cannot send one.")
		args := []string{"client: Client"}
		for _, p := range op.PathParams {
			args = append(args, p.TS+": "+tsType(p.Type))
		}
		fmt.Fprintf(b, "export function %sUrl(%s): string {\n  return client.socketUrl(%s)\n}\n", name, strings.Join(args, ", "), tsPathExpr(op))
		return
	}
	if len(op.QueryParams) > 0 {
		fmt.Fprintf(b, "/** The query parameters of %s. One left out is not sent. */\n", name)
		fmt.Fprintf(b, "export interface %sQuery {\n", op.Go)
		for _, q := range op.QueryParams {
			writeTSComment(b, "  ", q.Doc)
			fmt.Fprintf(b, "  %s?: %s\n", tsProperty(q.Name), tsType(q.Type))
		}
		b.WriteString("}\n\n")
	}
	args := []string{"client: Client"}
	for _, p := range op.PathParams {
		args = append(args, p.TS+": "+tsType(p.Type))
	}
	// A required body comes before the query, which may be left out.
	if op.Body != nil && op.BodyRequired {
		args = append(args, "body: "+tsType(op.Body))
	}
	if len(op.QueryParams) > 0 {
		args = append(args, "query?: "+op.Go+"Query")
	}
	if op.Body != nil && !op.BodyRequired {
		args = append(args, "body?: "+tsType(op.Body))
	}
	args = append(args, "options?: RequestOptions")
	result, accept := "void", "none"
	switch {
	case op.Content != "" && (strings.HasPrefix(op.Content, "text/") || op.Content == "application/yaml" || op.Content == "application/x-ndjson"):
		result, accept = "string", "text"
	case op.Content != "":
		result, accept = "ArrayBuffer", "bytes"
	case op.Response != nil:
		result, accept = tsType(op.Response), "json"
	}
	comment := operationComment(op, name)
	if op.Content != "" {
		comment += " The answer is " + op.Content + "."
	}
	writeTSComment(b, "", comment)
	if signature := fmt.Sprintf("export function %s(%s): Promise<%s> {", name, strings.Join(args, ", "), result); len(signature) <= 100 {
		b.WriteString(signature + "\n")
	} else {
		fmt.Fprintf(b, "export function %s(\n", name)
		for _, a := range args {
			b.WriteString("  " + a + ",\n")
		}
		fmt.Fprintf(b, "): Promise<%s> {\n", result)
	}
	call := []string{fmt.Sprintf("method: %q", op.Method), "path: " + tsPathExpr(op)}
	if len(op.QueryParams) > 0 {
		call = append(call, "query")
	}
	if op.Body != nil {
		call = append(call, "body")
	}
	call = append(call, fmt.Sprintf("accept: %q", accept))
	if op.Content != "" {
		call = append(call, fmt.Sprintf("contentType: %q", op.Content))
	}
	line := fmt.Sprintf("  return client.request<%s>({ %s }, options)", result, strings.Join(call, ", "))
	if len(line) <= 100 {
		b.WriteString(line + "\n}\n")
		return
	}
	fmt.Fprintf(b, "  return client.request<%s>(\n    {\n", result)
	for _, part := range call {
		b.WriteString("      " + part + ",\n")
	}
	b.WriteString("    },\n    options,\n  )\n}\n")
}
