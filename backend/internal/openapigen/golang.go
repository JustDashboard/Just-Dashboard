package openapigen

import (
	"bytes"
	_ "embed"
	"fmt"
	"go/format"
	"strings"
	"text/template"
)

// The Go client: types.go (a struct per object, a string type and its
// constants per vocabulary), operations.go (a method per operation on
// Client) and client.go (the runtime, from client.go.tmpl, with the error
// envelope's fields read off the document).

//go:embed client.go.tmpl
var goRuntime string

// goHeader opens every Go file: the line `go generate` and linters recognise
// as generated code, and how to regenerate it.
const goHeader = "// Code generated by openapigen from docs/api/deploy-openapi.json. DO NOT EDIT.\n" +
	"// Regenerate with: cd backend && JD_UPDATE_SDK=1 go test ./internal/api -run TestTheCommittedSDKsAreCurrent\n\n"

func generateGo(api *API, pkg string) (map[string][]byte, error) {
	files := map[string][]byte{}
	runtime, err := goRuntimeFile(api, pkg)
	if err != nil {
		return nil, err
	}
	files["client.go"] = runtime
	types, err := gofmt("types.go", goTypes(api, pkg))
	if err != nil {
		return nil, err
	}
	files["types.go"] = types
	ops, err := gofmt("operations.go", goOperations(api, pkg))
	if err != nil {
		return nil, err
	}
	files["operations.go"] = ops
	return files, nil
}

func gofmt(name string, src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("the generated %s does not parse: %w\n%s", name, err, src)
	}
	return out, nil
}

func goRuntimeFile(api *API, pkg string) ([]byte, error) {
	tmpl, err := template.New("client.go").Parse(goRuntime)
	if err != nil {
		return nil, err
	}
	var fields bytes.Buffer
	for _, f := range api.ErrorFields {
		writeGoComment(&fields, "\t", f.Doc)
		fmt.Fprintf(&fields, "\t%s %s `json:\"%s,omitempty\"`\n", f.Go, goType(f.Type), f.JSON)
	}
	var out bytes.Buffer
	out.WriteString(goHeader)
	err = tmpl.Execute(&out, map[string]any{
		"Package":     pkg,
		"Title":       api.Title,
		"BasePath":    api.BasePath,
		"ErrorFields": strings.TrimRight(fields.String(), "\n"),
		"HasPhrase":   hasField(api.ErrorFields, "Phrase"),
	})
	if err != nil {
		return nil, err
	}
	return gofmt("client.go", out.Bytes())
}

func hasField(fields []Field, goName string) bool {
	for _, f := range fields {
		if f.Go == goName {
			return true
		}
	}
	return false
}

// goType is a Go type for a value.
func goType(t *Type) string {
	var base string
	pointer := t.Nullable
	switch t.Kind {
	case KindAny:
		return "any"
	case KindString:
		base = "string"
	case KindInt64:
		base = "int64"
	case KindInt32:
		base = "int32"
	case KindFloat:
		base = "float64"
	case KindBool:
		base = "bool"
	case KindTime:
		base = "time.Time"
	case KindBytes:
		return "[]byte"
	case KindNamed:
		base = t.Name
	case KindArray:
		return "[]" + goType(t.Elem)
	case KindMap:
		return "map[string]" + goType(t.Elem)
	case KindUnion:
		return "json.RawMessage"
	}
	if pointer {
		return "*" + base
	}
	return base
}

// goTag is a field's JSON tag. A scalar or a pointer left at its zero value
// is left out of a request, which the API reads as that zero value anyway; a
// struct or a time is left out when it is its zero value; a list or a map is
// always sent, so an empty one is not mistaken for one never given.
func goTag(f Field, decls map[string]*Decl) string {
	opt := ""
	switch {
	case f.Type.Kind == KindArray, f.Type.Kind == KindMap, f.Type.Kind == KindBytes, f.Type.Kind == KindUnion, f.Type.Kind == KindAny:
	case f.Type.Nullable:
		opt = ",omitempty"
	case f.Type.Kind == KindTime:
		opt = ",omitzero"
	case f.Type.Kind == KindNamed && decls[f.Type.Name] != nil && decls[f.Type.Name].Enum == nil:
		opt = ",omitzero"
	default:
		opt = ",omitempty"
	}
	return fmt.Sprintf("`json:\"%s%s\"`", f.JSON, opt)
}

func goTypes(api *API, pkg string) []byte {
	decls := map[string]*Decl{}
	for _, d := range api.Decls {
		decls[d.Name] = d
	}
	var b bytes.Buffer
	b.WriteString(goHeader)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	imports := goImports(api, false)
	if len(imports) > 0 {
		b.WriteString("import (\n")
		for _, imp := range imports {
			fmt.Fprintf(&b, "\t%q\n", imp)
		}
		b.WriteString(")\n\n")
	}
	for _, d := range api.Decls {
		if d.Enum != nil {
			writeGoComment(&b, "", declComment(d, d.Name+" is one of the values of "+d.Source+"."))
			fmt.Fprintf(&b, "type %s string\n\n", d.Name)
			fmt.Fprintf(&b, "// The values of %s.\nconst (\n", d.Name)
			for _, name := range enumConstants(d) {
				fmt.Fprintf(&b, "\t%s %s = %q\n", name.ident, d.Name, name.value)
			}
			b.WriteString(")\n\n")
			continue
		}
		summary := d.Name + " is " + d.Source + " in the dashboard's source."
		if d.Inline {
			summary = d.Name + " is the object " + d.Source + " spells out."
		}
		writeGoComment(&b, "", declComment(d, summary))
		fmt.Fprintf(&b, "type %s struct {\n", d.Name)
		for _, f := range d.Fields {
			doc := f.Doc
			if f.WriteOnly && !strings.Contains(doc, "never read back") {
				doc = strings.TrimSpace(doc + " Write-only: it is sent and never read back.")
			}
			writeGoComment(&b, "\t", doc)
			fmt.Fprintf(&b, "\t%s %s %s\n", f.Go, goType(f.Type), goTag(f, decls))
		}
		b.WriteString("}\n\n")
	}
	return b.Bytes()
}

func declComment(d *Decl, summary string) string {
	if d.Doc == "" {
		return summary
	}
	return summary + "\n\n" + d.Doc
}

type enumConstant struct{ ident, value string }

// enumConstants names each value of a vocabulary as TypeValue.
func enumConstants(d *Decl) []enumConstant {
	used := map[string]bool{}
	out := make([]enumConstant, 0, len(d.Enum))
	for _, v := range d.Enum {
		ident := d.Name + exported(v)
		for n := 2; used[ident]; n++ {
			ident = fmt.Sprintf("%s%s%d", d.Name, exported(v), n)
		}
		used[ident] = true
		out = append(out, enumConstant{ident, v})
	}
	return out
}

// goImports is what a file needs from the standard library.
func goImports(api *API, operations bool) []string {
	need := map[string]bool{}
	var mark func(t *Type)
	mark = func(t *Type) {
		if t == nil {
			return
		}
		switch t.Kind {
		case KindTime:
			need["time"] = true
		case KindUnion:
			need["encoding/json"] = true
		case KindArray, KindMap:
			mark(t.Elem)
		}
	}
	if operations {
		need["context"] = true
		for _, op := range api.Ops {
			for _, p := range op.PathParams {
				switch p.Type.Kind {
				case KindInt64, KindInt32:
					need["strconv"] = true
				default:
					need["net/url"] = true
				}
			}
			for _, q := range op.QueryParams {
				need["net/url"] = true
				switch q.Type.Kind {
				case KindInt64, KindInt32, KindFloat, KindBool:
					need["strconv"] = true
				}
			}
			if op.Stream {
				continue
			}
			if op.Response != nil && (op.Response.Kind == KindUnion || op.Response.Kind == KindAny) {
				need["encoding/json"] = true
			}
			mark(op.Response)
			mark(op.Body)
		}
		if !needsContext(api) {
			delete(need, "context")
		}
	} else {
		for _, d := range api.Decls {
			for _, f := range d.Fields {
				mark(f.Type)
			}
		}
	}
	return sortedKeys(need)
}

func needsContext(api *API) bool {
	for _, op := range api.Ops {
		if !op.Stream {
			return true
		}
	}
	return false
}

func goOperations(api *API, pkg string) []byte {
	var b bytes.Buffer
	b.WriteString(goHeader)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	imports := goImports(api, true)
	if len(imports) > 0 {
		b.WriteString("import (\n")
		for _, imp := range imports {
			fmt.Fprintf(&b, "\t%q\n", imp)
		}
		b.WriteString(")\n\n")
	}
	for _, op := range api.Ops {
		if len(op.QueryParams) > 0 && !op.Stream {
			writeGoComment(&b, "", op.Go+"Params are the query parameters of "+op.Go+". A parameter left at its zero value is not sent.")
			fmt.Fprintf(&b, "type %sParams struct {\n", op.Go)
			for _, q := range op.QueryParams {
				writeGoComment(&b, "\t", q.Doc)
				fmt.Fprintf(&b, "\t%s %s\n", q.Go, goType(q.Type))
			}
			b.WriteString("}\n\n")
		}
		writeGoOperation(&b, op)
	}
	return b.Bytes()
}

// operationComment is what an operation's method says about itself: the
// summary, the note, the route and who may call it.
func operationComment(op *Operation, name string) string {
	var sb strings.Builder
	summary := op.Summary
	if summary != "" {
		summary = strings.ToLower(summary[:1]) + summary[1:]
	}
	sb.WriteString(name + " is " + op.Method + " " + op.Path + ": " + summary)
	if op.Description != "" {
		sb.WriteString("\n\n" + op.Description)
	}
	if note := accessNote(op); note != "" {
		sb.WriteString("\n\n" + note)
	}
	return sb.String()
}

// accessNote says who may call an operation, from its security and its
// x-deploy-key and x-destructive.
func accessNote(op *Operation) string {
	var parts []string
	switch {
	case op.Session:
		parts = append(parts, "Only an interactive session may call it; no key reaches it.")
	case op.DeployKey != "":
		parts = append(parts, "A deploy key: "+op.DeployKey+".")
	}
	if op.Destructive {
		parts = append(parts, "Destructive: it needs a role that may take destructive actions, and spends their budget.")
	}
	return strings.Join(parts, " ")
}

func writeGoOperation(b *bytes.Buffer, op *Operation) {
	pathExpr := goPathExpr(op)
	if op.Stream {
		writeGoComment(b, "", operationComment(op, op.Go+"URL")+
			"\n\nIt is a WebSocket stream rather than a call, so the client gives its address (ws:// or wss://) for a WebSocket client to dial with the key as a bearer token.")
		args := make([]string, 0, len(op.PathParams))
		for _, p := range op.PathParams {
			args = append(args, p.Go+" "+goType(p.Type))
		}
		fmt.Fprintf(b, "func (c *Client) %sURL(%s) string {\n\treturn c.socketURL(%s)\n}\n\n", op.Go, strings.Join(args, ", "), pathExpr)
		return
	}
	args := []string{"ctx context.Context"}
	for _, p := range op.PathParams {
		args = append(args, p.Go+" "+goType(p.Type))
	}
	if op.Body != nil {
		bodyType := goType(op.Body)
		if !op.BodyRequired && op.Body.Kind == KindNamed {
			bodyType = "*" + strings.TrimPrefix(bodyType, "*")
		}
		args = append(args, "body "+bodyType)
	}
	if len(op.QueryParams) > 0 {
		args = append(args, "params *"+op.Go+"Params")
	}
	args = append(args, "opts ...RequestOption")
	result, zero := "", ""
	switch {
	case op.Content != "":
		result, zero = "[]byte", "nil"
	case op.Response == nil:
	case op.Response.Kind == KindUnion || op.Response.Kind == KindAny:
		result, zero = "json.RawMessage", "nil"
	case op.Response.Kind == KindNamed:
		result, zero = "*"+strings.TrimPrefix(goType(op.Response), "*"), "nil"
	default:
		result, zero = goType(op.Response), "nil"
		switch op.Response.Kind {
		case KindString:
			zero = `""`
		case KindInt64, KindInt32, KindFloat:
			zero = "0"
		case KindBool:
			zero = "false"
		}
	}
	comment := operationComment(op, op.Go)
	if op.Content != "" {
		comment += " The answer is " + op.Content + ", returned as it came."
	}
	if op.Response != nil && op.Response.Kind == KindUnion {
		comment += "\n\nThe answer is one of " + goAlternatives(op.Response) + ", as the request chooses; decode it into the one asked for."
	}
	writeGoComment(b, "", comment)
	returns := "error"
	if result != "" {
		returns = "(" + result + ", error)"
	}
	fmt.Fprintf(b, "func (c *Client) %s(%s) %s {\n", op.Go, strings.Join(args, ", "), returns)
	query := "nil"
	if len(op.QueryParams) > 0 {
		query = "query"
		b.WriteString("\tquery := url.Values{}\n\tif params != nil {\n")
		for _, q := range op.QueryParams {
			b.WriteString(goQuerySet(q))
		}
		b.WriteString("\t}\n")
	}
	body := "nil"
	if op.Body != nil {
		if !op.BodyRequired && op.Body.Kind == KindNamed {
			b.WriteString("\tvar payload any\n\tif body != nil {\n\t\tpayload = body\n\t}\n")
			body = "payload"
		} else {
			body = "body"
		}
	}
	call := fmt.Sprintf("%q, %s, %s, %s", op.Method, pathExpr, query, body)
	switch {
	case op.Content != "":
		fmt.Fprintf(b, "\treturn c.raw(ctx, %s, %q, opts)\n", call, op.Content)
	case result == "":
		fmt.Fprintf(b, "\treturn c.do(ctx, %s, nil, opts)\n", call)
	case strings.HasPrefix(result, "*"):
		fmt.Fprintf(b, "\tvar out %s\n\tif err := c.do(ctx, %s, &out, opts); err != nil {\n\t\treturn nil, err\n\t}\n\treturn &out, nil\n", strings.TrimPrefix(result, "*"), call)
	default:
		fmt.Fprintf(b, "\tvar out %s\n\tif err := c.do(ctx, %s, &out, opts); err != nil {\n\t\treturn %s, err\n\t}\n\treturn out, nil\n", result, call, zero)
	}
	b.WriteString("}\n\n")
}

// goAlternatives names a union's types for a comment.
func goAlternatives(t *Type) string {
	names := make([]string, 0, len(t.Options))
	for _, o := range t.Options {
		names = append(names, goType(o))
	}
	if len(names) < 2 {
		return strings.Join(names, "")
	}
	return strings.Join(names[:len(names)-1], ", ") + " or " + names[len(names)-1]
}

// goPathExpr is an expression for an operation's path, its parameters
// escaped into it.
func goPathExpr(op *Operation) string {
	byName := map[string]Param{}
	for _, p := range op.PathParams {
		byName[p.Name] = p
	}
	var parts []string
	literal := ""
	path := op.Path
	for path != "" {
		open := strings.Index(path, "{")
		if open < 0 {
			literal += path
			break
		}
		closeAt := strings.Index(path[open:], "}")
		if closeAt < 0 {
			literal += path
			break
		}
		literal += path[:open]
		name := path[open+1 : open+closeAt]
		path = path[open+closeAt+1:]
		if literal != "" {
			parts = append(parts, fmt.Sprintf("%q", literal))
			literal = ""
		}
		p := byName[name]
		switch {
		case p.Type == nil:
			parts = append(parts, fmt.Sprintf("%q", "{"+name+"}"))
		case p.Type.Kind == KindInt64:
			parts = append(parts, "strconv.FormatInt("+p.Go+", 10)")
		case p.Type.Kind == KindInt32:
			parts = append(parts, "strconv.FormatInt(int64("+p.Go+"), 10)")
		case p.Type.Kind == KindNamed:
			parts = append(parts, "url.PathEscape(string("+p.Go+"))")
		default:
			parts = append(parts, "url.PathEscape("+p.Go+")")
		}
	}
	if literal != "" {
		parts = append(parts, fmt.Sprintf("%q", literal))
	}
	if len(parts) == 0 {
		return `""`
	}
	return strings.Join(parts, " + ")
}

func goQuerySet(q Param) string {
	field := "params." + q.Go
	switch q.Type.Kind {
	case KindInt64:
		return fmt.Sprintf("\t\tif %s != 0 {\n\t\t\tquery.Set(%q, strconv.FormatInt(%s, 10))\n\t\t}\n", field, q.Name, field)
	case KindInt32:
		return fmt.Sprintf("\t\tif %s != 0 {\n\t\t\tquery.Set(%q, strconv.FormatInt(int64(%s), 10))\n\t\t}\n", field, q.Name, field)
	case KindFloat:
		return fmt.Sprintf("\t\tif %s != 0 {\n\t\t\tquery.Set(%q, strconv.FormatFloat(%s, 'f', -1, 64))\n\t\t}\n", field, q.Name, field)
	case KindBool:
		return fmt.Sprintf("\t\tif %s {\n\t\t\tquery.Set(%q, \"true\")\n\t\t}\n", field, q.Name)
	case KindNamed:
		return fmt.Sprintf("\t\tif %s != \"\" {\n\t\t\tquery.Set(%q, string(%s))\n\t\t}\n", field, q.Name, field)
	}
	return fmt.Sprintf("\t\tif %s != \"\" {\n\t\t\tquery.Set(%q, %s)\n\t\t}\n", field, q.Name, field)
}

// writeGoComment writes text as a comment, wrapped at about a hundred
// columns, each paragraph kept.
func writeGoComment(b *bytes.Buffer, indent, text string) {
	text = strings.TrimSpace(text)
	if text == "" {
		return
	}
	for i, paragraph := range strings.Split(text, "\n\n") {
		if i > 0 {
			b.WriteString(indent + "//\n")
		}
		for _, line := range wrap(paragraph, 96-len(indent)) {
			b.WriteString(indent + "// " + line + "\n")
		}
	}
}

// wrap breaks a paragraph into lines of at most width characters, at spaces.
func wrap(paragraph string, width int) []string {
	var lines []string
	var line strings.Builder
	for _, word := range strings.Fields(paragraph) {
		if line.Len() > 0 && line.Len()+1+len(word) > width {
			lines = append(lines, line.String())
			line.Reset()
		}
		if line.Len() > 0 {
			line.WriteByte(' ')
		}
		line.WriteString(word)
	}
	if line.Len() > 0 {
		lines = append(lines, line.String())
	}
	return lines
}
