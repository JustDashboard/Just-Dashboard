func TestDetectAdblockAsContainerAndProcess(t *testing.T) {
	t.Parallel()
	containers := []DNSContainer{
		{Name: "adguard", Image: "adguard/adguardhome:latest", State: "running", Ports: []DNSPort{
			{Private: 53, Public: 53, Type: "udp"}, {Private: 53, Public: 53, Type: "tcp"},
			{Private: 3000, Public: 3001, Type: "tcp"}, {Private: 853, Public: 853, Type: "tcp"},
		}},
		{Name: "old-pihole", Image: "pihole/pihole", State: "exited"},
		{Name: "web", Image: "nginx", State: "running"},
	}
	listeners := []proxysvc.Listener{
		{Protocol: "udp", Address: "0.0.0.0", Port: 53, PID: 900, Process: "docker-proxy", Scope: proxysvc.ScopeAll},
		{Protocol: "udp", Address: "127.0.0.1", Port: 53, PID: 410, Process: "pihole-FTL", Scope: proxysvc.ScopeLoopback},
		{Protocol: "tcp", Address: "127.0.0.1", Port: 8080, PID: 410, Process: "pihole-FTL", Scope: proxysvc.ScopeLoopback},
		{Protocol: "tcp", Address: "127.0.0.1", Port: 4711, PID: 410, Process: "pihole-FTL", Scope: proxysvc.ScopeLoopback},
		{Protocol: "tcp", Address: "0.0.0.0", Port: 22, PID: 1, Process: "sshd"},
	}
	dns := dnsListeners(listeners)
	if len(dns) != 2 || dns[0].Kind != "docker-proxy" || dns[1].Kind != "pihole" || !dns[1].Loopback || dns[0].Loopback {
		t.Fatalf("listeners = %+v", dns)
	}
	got := detectAdblock(containers, listeners, dns)
	if len(got) != 2 {
		t.Fatalf("adblock = %+v", got)
	}
	if a := got[0]; a.Kind != "adguardhome" || a.RunsAs != "container" || a.Container != "adguard" || !a.Answering || a.WebPort != 3001 {
		t.Fatalf("container = %+v", a)
	}
	if a := got[1]; a.Kind != "pihole" || a.RunsAs != "process" || !a.Answering || a.WebPort != 8080 {
		t.Fatalf("process = %+v (4711 is FTL's API, 8080 its web page)", a)
	}
}

