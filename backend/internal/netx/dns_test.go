// pointResolvConf makes /etc/resolv.conf a file the test owns. "stub" is the
// link Ubuntu ships, "uplink" the one to the uplink servers, "static" a plain
// file with a header NetworkManager would have written.
func pointResolvConf(t *testing.T, mode string) string {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, "resolv.conf")
	switch mode {
	case "stub":
		if err := os.Symlink("../run/systemd/resolve/stub-resolv.conf", path); err != nil {
			t.Fatal(err)
		}
	case "uplink":
		if err := os.Symlink("../run/systemd/resolve/resolv.conf", path); err != nil {
			t.Fatal(err)
		}
	default:
		body := "# Generated by NetworkManager\nsearch example.internal\nnameserver 198.51.100.53\nnameserver 198.51.100.54\noptions timeout:2\n"
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	prev := resolvConfPath
	resolvConfPath = path
	t.Cleanup(func() { resolvConfPath = prev })
	return path
}

